"""Nightly implementer (Phase 2) — turns synthesizer code proposals into draft PRs.

Runs AFTER the synthesizer when its report carries ``code_improvements``:
one Claude Agent SDK session (same ``pontifex.agent`` harness as the
analyst/synthesizer, subscription-billed) gets throwaway clones of the
target repos, implements the top proposals, verifies what it can, and
opens DRAFT pull requests — never merging, never touching main.

Safety model:
- The session works only in freshly-cloned workspaces under a temp dir
  (``/repos`` is a read-only mount; clones are made from it, so no
  network is needed to obtain sources).
- Pushes go to ``nightly/...`` branches via the ``GITHUB_TOKEN`` env; the
  system prompt carries explicit STOP-on-fail gates, and every PR is a
  draft that states exactly what verification ran.
- The whole run is bounded by ``total_timeout_s`` and ``max_turns``; a
  failed or empty session records an outcome and the night continues.

Every run is persisted through :class:`ImplementerReportStore` (a sidecar
SQLite DB) so what got opened, skipped, and dropped survives past the
email/logs — including the proposals the cap couldn't fit.
"""
import json
import logging
import shutil
import sqlite3
import subprocess
import tempfile
import threading
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import httpx
from pontifex.agent import AgentRunConfig, AgentSession
from pontifex.codex import CodexRunConfig, CodexSession

from telos.services.nightly.sandbox_preflight import check_codex_sandbox
from telos.services.nightly.synth_schemas import ImprovementReport
from telos.services.nightly.worker_client import WorkerSession

log = logging.getLogger("telos.services.nightly")

_SEVERITY_ORDER = {"high": 0, "normal": 1, "low": 2}

IMPLEMENTER_SYSTEM = """You are the nightly implementer for a personal multi-agent platform (telos: agents/UI; Recordatio: memory engine). You receive code-improvement proposals produced tonight by a diagnostic synthesizer from real production evidence. Your job: implement the ones you can fully ground in the code, and open DRAFT pull requests. You work unsupervised — the rules below are hard gates, not suggestions. If any gate fails, STOP that proposal and record it as skipped with the reason; never improvise around a gate.

HARD RULES:
- Work ONLY inside the workspace clones listed in the task. Never modify anything outside them.
- NEVER push to main/master or any existing branch. Push only NEW branches named nightly/<date>-<short-slug>.
- Every PR you open MUST be a draft.
- Implement a proposal only if you can confirm its diagnosis in the actual code. If the proposal is ambiguous, requires a design decision, or the code doesn't match its description — skip it and say why.
- One focused PR per proposal: minimal diff, no drive-by refactors, match the surrounding code style. Include a regression test that fails without the fix whenever the repo's test layout allows it.
- VERIFICATION GATES before opening each PR:
  * telos repo: create a venv with the locked runtime and all test dependencies (`python -m venv .venv-check && .venv-check/bin/pip install -r requirements.txt -e '.[dev,ui]' -q`), run the full suite with its home/data inside the clone (`mkdir -p .nightly-test-home && HOME="$PWD/.nightly-test-home" STORAGE_ROOT="$PWD/.nightly-test-home/.telos" .venv-check/bin/python -m pytest tests/ -q`). Never commit the venv or test-home directory. All tests must pass. If installation or tests fail for reasons unrelated to your change, STOP and skip the proposal.
  * Recordatio repo: the full suite cannot run here (heavy ML dependencies). Run `python -m py_compile` on every changed file, and if ruff is installable (`pip install ruff -q`), `ruff check` on them. The PR body MUST state exactly what was and was NOT verified.
- PR body: lead with WHY (the recurring production failure the proposal cites), then What/How/Testing. End with: "Auto-generated by the nightly implementer from a synthesizer proposal — needs human review before merge."
- Push with: git push https://x-access-token:${GITHUB_TOKEN}@github.com/<repo-slug>.git HEAD:refs/heads/<branch>
- Open the PR with the GitHub REST API using python + httpx (both available), POST /repos/<repo-slug>/pulls with {"draft": true, "base": "main", ...}; the token is in the GITHUB_TOKEN env var.
- If a push or PR call is rejected (permissions, protection rules), record the proposal as skipped with the error — do not retry with different refs.

When done, report every proposal as either an opened PR (with its URL and what verification ran) or a skip (with the reason)."""


IMPL_OUTPUT_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "summary": {"type": "string"},
        "prs": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "repo": {"type": "string"},
                    "branch": {"type": "string"},
                    "url": {"type": "string"},
                    "title": {"type": "string"},
                    "verification": {"type": "string"},
                },
                "required": ["repo", "branch", "url", "title", "verification"],
            },
        },
        "skipped": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "title": {"type": "string"},
                    "reason": {"type": "string"},
                },
                "required": ["title", "reason"],
            },
        },
    },
    "required": ["summary", "prs", "skipped"],
}


@dataclass
class ImplementerCandidate:
    """One proposal in the implementer's pool.

    Code improvements arrive with a ``repo``/``files`` the synthesizer
    already grounded. UX improvements have neither (the synthesizer's UX
    section carries only title/detail), so ``ux_origin`` items are handed
    to the session to locate the repo/files itself — and skipped with a
    reason if they turn out not to be code-actionable.
    """

    title: str
    detail: str
    severity: str = "normal"
    repo: str | None = None
    files: list[str] = field(default_factory=list)
    ux_origin: bool = False


@dataclass
class ProposalSelection:
    """What :meth:`NightlyImplementer.select_proposals` decided.

    ``selected`` is the severity-prioritized pool the session works on;
    ``dropped`` is everything left out (unknown-repo code proposals and
    anything beyond the cap), each with a human-readable ``reason`` so the
    run can record and surface it instead of losing it silently.
    """

    selected: list[ImplementerCandidate] = field(default_factory=list)
    dropped: list[dict[str, Any]] = field(default_factory=list)


class ImplementerReportStore:
    """Persists implementer outcomes (sidecar table in its own DB).

    Mirrors ``SynthReportStore``: WAL-mode SQLite guarded by a lock so the
    async cron and any read route can share one connection. Each run —
    including the no-proposals / no-token / clone-failure early exits —
    lands one row with the PRs opened, the skips, and the cap-dropped
    proposals so nothing the night decided is lost to email/logs alone.
    """

    def __init__(self, db_path: Path) -> None:
        db_path.parent.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()
        self._conn = sqlite3.connect(str(db_path), check_same_thread=False)
        self._conn.row_factory = sqlite3.Row
        self._conn.execute("PRAGMA journal_mode=WAL")
        self._conn.executescript(
            """
            CREATE TABLE IF NOT EXISTS implementer_reports (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                created_at TEXT NOT NULL,
                summary TEXT NOT NULL,
                prs_json TEXT NOT NULL DEFAULT '[]',
                skipped_json TEXT NOT NULL DEFAULT '[]',
                cap_dropped_json TEXT NOT NULL DEFAULT '[]',
                cost_usd REAL NOT NULL DEFAULT 0.0,
                error TEXT
            );
            """
        )
        self._conn.commit()

    def record(self, *, summary: str, prs: list[dict[str, Any]], skipped: list[dict[str, Any]],
               cap_dropped: list[dict[str, Any]], cost_usd: float, error: str | None = None) -> int:
        with self._lock, self._conn:
            cur = self._conn.execute(
                "INSERT INTO implementer_reports "
                "(created_at, summary, prs_json, skipped_json, cap_dropped_json, cost_usd, error) "
                "VALUES (?, ?, ?, ?, ?, ?, ?)",
                (datetime.now(UTC).isoformat(), summary, json.dumps(prs),
                 json.dumps(skipped), json.dumps(cap_dropped), cost_usd, error),
            )
            return int(cur.lastrowid or 0)

    def list_reports(self, *, limit: int = 30) -> list[sqlite3.Row]:
        return self._conn.execute(
            "SELECT * FROM implementer_reports ORDER BY id DESC LIMIT ?", (limit,)
        ).fetchall()


def implementer_task_prompt(
    candidates: list[ImplementerCandidate],
    clones: dict[str, Path],
    repo_slugs: dict[str, str],
    branch_date: str,
) -> str:
    code_items = [
        {
            "repo": c.repo,
            "title": c.title,
            "severity": c.severity,
            "detail": c.detail,
            "files": c.files,
        }
        for c in candidates
        if not c.ux_origin
    ]
    ux_items = [
        {"title": c.title, "severity": c.severity, "detail": c.detail}
        for c in candidates
        if c.ux_origin
    ]
    workspaces = {name: str(path) for name, path in clones.items()}
    parts = [
        "Tonight's code-improvement proposals (already evidence-grounded by the synthesizer):\n"
        f"{json.dumps(code_items, indent=2)}\n"
    ]
    if ux_items:
        parts.append(
            "\nUX-origin candidates (locate the repo/files yourself; if not code-actionable, skip with a reason). "
            "These came from the synthesizer's UX section and carry no repo/files — confirm the mechanism in the "
            "actual code before implementing, and note the UX origin in the PR or skip reason:\n"
            f"{json.dumps(ux_items, indent=2)}\n"
        )
    parts.append(
        f"\nWorkspace clones (already checked out at current main): {json.dumps(workspaces, indent=2)}\n"
        f"GitHub slugs for push/PR: {json.dumps({k: v for k, v in repo_slugs.items() if k in workspaces})}\n"
        f"Branch prefix for tonight: nightly/{branch_date}-\n\n"
        "Confirm each diagnosis in the code, implement what holds up, verify per the gates, "
        "open draft PRs, and report every proposal (code and UX-origin) as a PR or a skip."
    )
    return "".join(parts)


@dataclass
class ImplementerOutcome:
    prs: list[dict[str, Any]] = field(default_factory=list)
    skipped: list[dict[str, Any]] = field(default_factory=list)
    cap_dropped: list[dict[str, Any]] = field(default_factory=list)
    summary: str = ""
    cost_usd: float = 0.0
    error: str | None = None


class NightlyImplementer:
    """One SDK session per night that turns code proposals into draft PRs."""

    def __init__(
        self,
        *,
        model: str,
        repo_roots: dict[str, Path],
        repo_slugs: dict[str, str],
        github_token: str,
        report_store: ImplementerReportStore,
        email_sink: Callable[[str, str, str], None] | None = None,
        owner_email: str | None = None,
        max_prs: int = 10,
        max_turns: int = 120,
        total_timeout_s: float = 5400.0,
        session: AgentSession | CodexSession | None = None,
        provider: str = "claude",
        worker_url: str = "",
        worker_token: str = "",
        workspace_root: Path | None = None,
    ) -> None:
        if provider not in {"claude", "codex"}:
            raise ValueError(f"Unknown provider: {provider}")
        if worker_url and (len(worker_token) < 32 or workspace_root is None):
            raise ValueError("Remote implementer requires a worker token and shared workspace root")
        self._worker_url = worker_url
        self._worker_token = worker_token
        self._workspace_root = workspace_root if worker_url else None
        self._provider = provider
        self._model = model
        self._repo_roots = repo_roots
        self._repo_slugs = repo_slugs
        self._github_token = github_token
        self._report_store = report_store
        self._email_sink = email_sink
        self._owner_email = owner_email
        self._max_prs = max_prs
        self._max_turns = max_turns
        self._total_timeout_s = total_timeout_s
        self._session = session or (CodexSession() if provider == "codex" else AgentSession())

    def select_proposals(self, report: ImprovementReport) -> ProposalSelection:
        """Severity-prioritized candidate pool (code + UX), capped at ``max_prs``.

        Nothing is dropped silently: unknown-repo code proposals and
        anything past the cap come back in ``dropped`` with a reason so
        ``run`` can persist, log, and email them. UX improvements have no
        repo/files, so they always enter the pool (the session locates the
        repo) and the cap applies to the combined, severity-sorted list.
        """
        known: list[ImplementerCandidate] = []
        dropped: list[dict[str, Any]] = []
        for c in report.code_improvements:
            if c.repo in self._repo_roots and c.repo in self._repo_slugs:
                known.append(ImplementerCandidate(
                    title=c.title, detail=c.detail, severity=c.severity,
                    repo=c.repo, files=list(c.files),
                ))
            else:
                dropped.append({
                    "title": c.title, "repo": c.repo, "severity": c.severity,
                    "ux_origin": False, "reason": f"unknown repo {c.repo!r}",
                })
        for u in report.ux_improvements:
            known.append(ImplementerCandidate(
                title=u.title, detail=u.detail, severity="normal", ux_origin=True,
            ))
        known.sort(key=lambda c: _SEVERITY_ORDER.get(c.severity, 9))
        selected = known[: self._max_prs]
        for c in known[self._max_prs:]:
            dropped.append({
                "title": c.title, "repo": c.repo, "severity": c.severity,
                "ux_origin": c.ux_origin, "reason": f"beyond max_prs cap of {self._max_prs}",
            })
        return ProposalSelection(selected=selected, dropped=dropped)

    def _prepare_clones(self, repos: set[str], workdir: Path) -> dict[str, Path]:
        """Fresh clone per target repo from the (read-only) local roots."""
        clones: dict[str, Path] = {}
        for name in sorted(repos):
            dest = workdir / name
            subprocess.run(
                ["git", "clone", "--quiet", str(self._repo_roots[name]), str(dest)],
                check=True, capture_output=True, text=True, timeout=300,
            )
            clones[name] = dest
        return clones

    async def run(self, report: ImprovementReport) -> ImplementerOutcome:
        selection = self.select_proposals(report)
        proposals = selection.selected
        cap_dropped = selection.dropped
        for d in cap_dropped:
            log.warning("implementer: dropping proposal %r (repo=%s): %s",
                        d.get("title"), d.get("repo"), d.get("reason"))

        if not proposals:
            return self._finalize(ImplementerOutcome(
                summary="no eligible code proposals", cap_dropped=cap_dropped,
            ))
        if not self._github_token:
            return self._finalize(ImplementerOutcome(
                error="GITHUB_TOKEN not configured", summary="skipped: no token",
                cap_dropped=cap_dropped,
            ))

        if self._workspace_root is not None:
            self._workspace_root.mkdir(parents=True, exist_ok=True)
        workdir = Path(tempfile.mkdtemp(prefix="nightly-impl-", dir=self._workspace_root))
        worker = WorkerSession(self._worker_url, self._worker_token, self._provider) if self._worker_url else None
        try:
            if worker or self._provider == "codex":
                failure = await worker.preflight(workdir) if worker else await check_codex_sandbox(workdir)
                if failure:
                    return self._finalize(ImplementerOutcome(
                        error=failure, summary="Infrastructure blocked: workspace sandbox preflight failed before code inspection; no model session started.",
                        skipped=[{"title": p.title, "reason": failure} for p in proposals],
                        cap_dropped=cap_dropped,
                    ))
            # Clone the repos the code proposals name; when a UX-origin
            # candidate is in the pool it has no repo, so make every known
            # repo available for the session to locate its target in.
            repos_to_clone = {p.repo for p in proposals if p.repo}
            if any(p.ux_origin for p in proposals):
                repos_to_clone |= {r for r in self._repo_roots if r in self._repo_slugs}
            clones = self._prepare_clones(repos_to_clone, workdir)
            branch_date = datetime.now(UTC).strftime("%Y%m%d")
            if self._provider == "codex":
                config = CodexRunConfig(
                    model=self._model, cwd=str(workdir), output_schema=IMPL_OUTPUT_SCHEMA,
                    workspace_write=True, network_access=True, max_tool_calls=self._max_turns,
                    extra_env={"GITHUB_TOKEN": self._github_token}, total_timeout_s=self._total_timeout_s,
                )
            else:
                config = AgentRunConfig(
                    model=self._model,
                    max_turns=self._max_turns,
                    allowed_tools=["Read", "Edit", "Write", "Bash", "Glob", "Grep"],
                    cwd=str(workdir),
                    output_schema=IMPL_OUTPUT_SCHEMA,
                    extra_env={"GITHUB_TOKEN": self._github_token},
                    total_timeout_s=self._total_timeout_s,
                )
            outcome = await (worker or self._session).run(
                config=config,
                system_prompt=IMPLEMENTER_SYSTEM,
                prompt=implementer_task_prompt(proposals, clones, self._repo_slugs, branch_date),
            )
            structured = outcome.structured_output if isinstance(outcome.structured_output, dict) else {}
            return self._finalize(ImplementerOutcome(
                prs=list(structured.get("prs") or []),
                skipped=list(structured.get("skipped") or []),
                cap_dropped=cap_dropped,
                summary=str(structured.get("summary") or ""),
                cost_usd=outcome.cost_usd,
                error=outcome.error,
            ))
        except subprocess.CalledProcessError as exc:
            log.exception("implementer: workspace clone failed")
            return self._finalize(ImplementerOutcome(
                error=f"clone failed: {exc.stderr or exc}", summary="workspace setup failed",
                cap_dropped=cap_dropped,
            ))
        except (httpx.HTTPError, OSError, RuntimeError, ValueError) as exc:
            failure = f"Coding worker failed: {type(exc).__name__}: {exc}"
            log.exception("implementer: execution failed")
            return self._finalize(ImplementerOutcome(
                error=failure, summary="implementation failed",
                skipped=[{"title": p.title, "reason": failure} for p in proposals], cap_dropped=cap_dropped,
            ))
        finally:
            if worker is None or worker.cleanup_safe:
                shutil.rmtree(workdir, ignore_errors=True)
            else:
                log.error("implementer: worker termination unconfirmed; preserving workspace %s", workdir)

    def _finalize(self, result: ImplementerOutcome) -> ImplementerOutcome:
        """Persist the outcome, email a summary, and return it."""
        self._record(result)
        self._send_email(result)
        return result

    def _record(self, result: ImplementerOutcome) -> None:
        try:
            self._report_store.record(
                summary=result.summary, prs=result.prs, skipped=result.skipped,
                cap_dropped=result.cap_dropped, cost_usd=result.cost_usd, error=result.error,
            )
        except Exception:
            log.exception("implementer: recording outcome failed")

    def _send_email(self, result: ImplementerOutcome) -> None:
        if self._email_sink is None or not self._owner_email:
            return
        if not result.prs and not result.skipped and not result.cap_dropped:
            return
        try:
            lines = ["<h2>Nightly implementer</h2>", f"<p>{result.summary}</p>"]
            if result.prs:
                lines.append(f"<p><strong>{len(result.prs)} draft PR(s) opened — review before merge.</strong></p><ul>")
                lines.extend(
                    f'<li><a href="{pr.get("url", "")}">[{pr.get("repo", "?")}] {pr.get("title", "?")}</a>'
                    f"<br><em>Verification:</em> {pr.get('verification', 'not stated')}</li>"
                    for pr in result.prs
                )
                lines.append("</ul>")
            if result.skipped:
                lines.append("<h3>Skipped</h3><ul>")
                lines.extend(
                    f"<li><strong>{s.get('title', '?')}</strong> — {s.get('reason', '')}</li>"
                    for s in result.skipped
                )
                lines.append("</ul>")
            if result.cap_dropped:
                lines.append("<h3>Not attempted (cap / unknown repo)</h3><ul>")
                lines.extend(
                    f"<li><strong>{d.get('title', '?')}</strong>"
                    f"{' (UX-origin)' if d.get('ux_origin') else ''} — {d.get('reason', '')}</li>"
                    for d in result.cap_dropped
                )
                lines.append("</ul>")
            self._email_sink(self._owner_email, "Nightly implementer: draft PRs", "\n".join(lines))
        except Exception:
            log.exception("implementer: email failed")


